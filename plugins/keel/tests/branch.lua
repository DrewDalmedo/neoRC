-- lua/neo/plugins/keel/tests/branch.lua
local function current(t, repo)
    return vim.trim(t.git(repo, "branch", "--show-current"))
end

-- A repository with a bare remote it's already tracking.
local function with_remote(t)
    local repo = t.repo({ f = "a\n" })
    local bare = repo .. "-remote.git"
    vim.fn.mkdir(bare, "p")
    t.git(bare, "init", "-q", "--bare")
    t.git(repo, "remote", "add", "origin", bare)
    t.git(repo, "push", "-qu", "origin", "main")
    return repo, bare
end

local function query(c, text)
    c.keys(text)
    c.lua("vim.wait(120)")
end

return function(t)
    t.child(function(c)
        local repo = t.repo({ f = "a\n" })
        t.git(repo, "branch", "feature-x")
        c.open(repo)
        c.keys("b")
        c.lua("vim.wait(80)")
        t.eq("b opens the picker", c.lua("return vim.bo.filetype"), "picker_prompt")
        query(c, "feature")
        c.keys("<CR>")
        t.eq("switches branch", current(t, repo), "feature-x")
        t.ok("status follows", c.has("Head:     feature-x"))
    end)

    t.child(function(c) -- creating from the query
        local repo = t.repo({ f = "a\n" })
        c.open(repo)
        c.keys("b")
        c.lua("vim.wait(80)")
        query(c, "brand-new")
        c.keys("<C-n>")
        c.lua("vim.wait(50)")
        c.settle()
        t.eq("creates and switches", current(t, repo), "brand-new")
    end)

    t.child(function(c) -- a refused switch keeps your work
        local repo = t.repo({ f = "a\n" })
        t.git(repo, "switch", "-qc", "other")
        t.write(repo, "f", "other\n")
        t.git(repo, "commit", "-qam", "other")
        t.git(repo, "switch", "-q", "main")
        t.write(repo, "f", "uncommitted\n")
        c.open(repo)
        c.keys("b")
        c.lua("vim.wait(80)")
        query(c, "other")
        c.keys("<CR>")
        t.eq("stays on the branch", current(t, repo), "main")
        t.eq("work is untouched", t.read(repo, "f"), "uncommitted\n")
        t.ok("git's reason shown", c.lua([[return table.concat(notes, "\n"):find("switch failed", 1, true) ~= nil]]))
    end)

    t.child(function(c) -- a remote branch gets a tracking branch
        local repo, bare = with_remote(t)
        t.git(repo, "switch", "-qc", "remote-only")
        t.git(repo, "push", "-q", "origin", "remote-only")
        t.git(repo, "switch", "-q", "main")
        t.git(repo, "branch", "-qD", "remote-only")
        c.open(repo)
        c.keys("b")
        c.lua("vim.wait(80)")
        query(c, "origin/remote")
        c.keys("<CR>")
        t.eq("creates the local branch", current(t, repo), "remote-only")
        t.eq("it tracks the remote", vim.trim(t.git(repo, "rev-parse", "--abbrev-ref", "@{u}")), "origin/remote-only")
        local _ = bare
    end)

    t.child(function(c) -- push
        local repo, bare = with_remote(t)
        t.write(repo, "f", "b\n")
        t.git(repo, "commit", "-qam", "to push")
        c.open(repo)
        t.ok("shows ahead", c.has("ahead 1"))
        local windows = c.lua("return #vim.api.nvim_list_wins()")
        c.keys("P")
        t.eq("pushed", vim.trim(t.git(bare, "log", "-1", "--format=%s", "main")), "to push")
        t.eq("the terminal closes", c.lua("return #vim.api.nvim_list_wins()"), windows)
        t.eq("back in status", c.lua("return vim.bo.filetype"), "keelstatus")
        t.eq("not left in Terminal mode", c.mode(), "n")
        t.ok("no longer ahead", not c.has("ahead 1"))
    end)

    t.child(function(c) -- a new branch asks before publishing
        local repo, bare = with_remote(t)
        t.git(repo, "switch", "-qc", "topic")
        c.open(repo)
        c.keys("P")
        t.eq("asks first", c.lua("return vim.bo.filetype"), "malleable_confirm")
        t.ok("names the branch and remote", c.has("Push topic to origin"))
        c.keys("n")
        local refs = t.git(bare, "for-each-ref", "--format=%(refname)")
        t.ok("No publishes nothing", not refs:find("topic", 1, true))
        c.keys("P")
        c.keys("y")
        refs = t.git(bare, "for-each-ref", "--format=%(refname)")
        t.ok("Yes publishes", refs:find("refs/heads/topic", 1, true))
        t.eq("and tracks", vim.trim(t.git(repo, "rev-parse", "--abbrev-ref", "@{u}")), "origin/topic")
    end)

    t.child(function(c) -- fetch and pull
        local repo, bare = with_remote(t)
        local other = t.tmp .. "/other-clone"
        vim.fn.delete(other, "rf")
        t.git(t.tmp, "clone", "-q", bare, other)
        t.write(other, "f", "from elsewhere\n")
        t.git(other, "commit", "-qam", "elsewhere")
        t.git(other, "push", "-q")
        c.open(repo)
        c.keys("f")
        t.ok("fetch shows behind", c.has("behind 1"))
        t.eq("fetch leaves the file", t.read(repo, "f"), "a\n")
        c.keys("F")
        t.eq("pull updates the file", t.read(repo, "f"), "from elsewhere\n")
        t.ok("no longer behind", not c.has("behind 1"))
    end)

    t.child(function(c) -- open files follow a switch and a pull
        local repo, bare = with_remote(t)
        t.git(repo, "switch", "-qc", "other")
        t.write(repo, "f", "on other\n")
        t.git(repo, "commit", "-qam", "other")
        t.git(repo, "switch", "-q", "main")
        c.lua([[vim.cmd("edit " .. vim.fn.fnameescape(...))]], repo .. "/f")
        local buf = c.lua("return vim.api.nvim_get_current_buf()")
        local function open_text()
            c.lua("vim.wait(60)")
            return c.lua("return vim.api.nvim_buf_get_lines(..., 0, -1, false)", buf)
        end
        c.open(repo)
        c.keys("b")
        c.lua("vim.wait(80)")
        query(c, "other")
        c.keys("<CR>")
        t.eq("a switch reloads the open file", open_text(), { "on other" })

        t.git(repo, "switch", "-q", "main")
        c.keys("gr")
        c.lua("require('neo.plugins.keel.git').reload_buffers()")
        t.eq("back on main", open_text(), { "a" })
        local clone = t.tmp .. "/reload-clone"
        vim.fn.delete(clone, "rf")
        t.git(t.tmp, "clone", "-q", bare, clone)
        t.write(clone, "f", "pulled\n")
        t.git(clone, "commit", "-qam", "upstream")
        t.git(clone, "push", "-q")
        c.keys("F")
        t.eq("a pull reloads the open file", open_text(), { "pulled" })
    end)

    t.child(function(c) -- unsaved edits are never overwritten by a reload
        local repo = t.repo({ f = "a\n" })
        t.git(repo, "switch", "-qc", "other")
        t.write(repo, "f", "other\n")
        t.git(repo, "commit", "-qam", "other")
        t.git(repo, "switch", "-q", "main")
        c.lua([[
            vim.cmd("edit " .. vim.fn.fnameescape(...))
            vim.api.nvim_buf_set_lines(0, 0, -1, false, { "unsaved edit" })
        ]], repo .. "/f")
        local buf = c.lua("return vim.api.nvim_get_current_buf()")
        c.open(repo)
        c.keys("b")
        c.lua("vim.wait(80)")
        query(c, "other")
        c.keys("<CR>")
        c.lua("vim.wait(60)")
        t.eq("the switch happened", current(t, repo), "other")
        t.eq("unsaved edits stay", c.lua("return vim.api.nvim_buf_get_lines(..., 0, -1, false)", buf), { "unsaved edit" })
        t.eq("still marked unsaved", c.lua("return vim.bo[...].modified", buf), true)
    end)

    t.child(function(c) -- a failure stays on screen
        local repo = t.repo({ f = "a\n" })
        t.git(repo, "remote", "add", "origin", t.tmp .. "/no-such-remote.git")
        c.open(repo)
        c.keys("f")
        c.lua("vim.wait(100)")
        t.ok("reports the failure", c.lua([[return table.concat(notes, "\n"):find("fetch failed", 1, true) ~= nil]]))
        t.eq("the terminal stays open", c.lua("return vim.bo.buftype"), "terminal")
    end)

    t.child(function(c)
        local repo = t.repo({ f = "a\n" })
        c.open(repo)
        c.keys("P")
        t.ok("no remotes is explained", c.lua([[return table.concat(notes, "\n"):find("no remotes", 1, true) ~= nil]]))
        t.eq("nothing opens", c.lua("return vim.bo.filetype"), "keelstatus")
    end)
end
