-- lua/neo/plugins/keel/tests/commit.lua
local function count(t, repo)
    return tonumber(vim.trim(t.git(repo, "rev-list", "--count", "HEAD")))
end

local function subject(t, repo)
    return vim.trim(t.git(repo, "log", "-1", "--format=%s"))
end

local function hook(t, repo, name, body)
    t.write(repo, ".git/hooks/" .. name, "#!/bin/sh\n" .. body .. "\n")
    vim.fn.setfperm(repo .. "/.git/hooks/" .. name, "rwxr-xr-x")
end

-- A repository with one staged change, its status view open.
local function staged(t, c)
    local repo = t.repo({ f = "a\n" })
    t.write(repo, "f", "b\n")
    t.git(repo, "add", "f")
    c.open(repo)
    return repo
end

return function(t)
    t.child(function(c)
        local repo = staged(t, c)
        local windows = c.lua("return #vim.api.nvim_list_wins()")
        c.keys("cc")
        t.eq("commit buffer filetype", c.lua("return vim.bo.filetype"), "gitcommit")
        t.eq("an empty message starts in Insert", c.mode(), "i")
        t.ok("hints are in the winbar", c.lua("return vim.wo.winbar"):find("commit", 1, true))
        t.eq("hints aren't in the text", c.lines(), { "" })
        c.keys("Fix the thing<Esc>")
        c.keys("<C-c><C-c>")
        t.eq("committed", count(t, repo), 2)
        t.eq("with the message", subject(t, repo), "Fix the thing")
        t.eq("the split closes", c.lua("return #vim.api.nvim_list_wins()"), windows)
        t.eq("back in status", c.lua("return vim.bo.filetype"), "keelstatus")
        t.ok("status updated", not c.has("Staged changes"))
        t.ok("shows the new commit", c.has("Fix the thing"))
    end)

    t.child(function(c) -- from Insert mode
        local repo = staged(t, c)
        c.keys("cc")
        c.keys("From insert")
        c.keys("<C-c><C-c>")
        t.eq("commits from Insert", subject(t, repo), "From insert")
        t.eq("leaves Insert", c.mode(), "n")
    end)

    t.child(function(c) -- refusals
        local repo = t.repo({ f = "a\n" })
        c.open(repo)
        c.keys("cc")
        t.eq("nothing staged: stays in status", c.lua("return vim.bo.filetype"), "keelstatus")
        t.ok("says so", c.lua([[return table.concat(notes, "\n"):find("nothing staged", 1, true) ~= nil]]))
    end)

    t.child(function(c)
        local repo = staged(t, c)
        c.keys("cc")
        c.keys("<Esc>")
        c.keys("<C-c><C-c>")
        t.eq("empty message refused", count(t, repo), 1)
        t.eq("buffer stays", c.lua("return vim.bo.filetype"), "gitcommit")
    end)

    t.child(function(c) -- :w is a draft, never a commit
        local repo = staged(t, c)
        c.keys("cc")
        c.keys("Draft text<Esc>")
        c.keys(":w<CR>")
        t.eq(":w doesn't commit", count(t, repo), 1)
        t.eq(":w clears modified", c.lua("return vim.bo.modified"), false)
        t.eq("draft saved", t.read(repo, ".git/KEEL_COMMIT_DRAFT"), "Draft text\n")
        c.keys(":wq<CR>")
        t.eq(":wq closes the window", c.lua("return vim.bo.filetype"), "keelstatus")
        t.eq(":wq doesn't commit", count(t, repo), 1)

        c.lua([[vim.cmd("bwipeout! keel://commit/" .. vim.fn.fnameescape(...))]], repo)
        c.keys("cc")
        t.eq("draft comes back", c.lines(), { "Draft text" })
        c.keys("oSecond line<Esc>")
        c.keys(":e!<CR>")
        t.eq(":e! returns to the draft", c.lines(), { "Draft text" })
        c.keys("<C-c><C-c>")
        t.eq("commits the draft", subject(t, repo), "Draft text")
        t.eq("draft removed", t.read(repo, ".git/KEEL_COMMIT_DRAFT"), nil)
    end)

    t.child(function(c) -- abort
        local repo = staged(t, c)
        c.keys("cc")
        c.keys("Maybe<Esc>")
        c.keys("<C-c><C-k>")
        t.eq("abort asks", c.lua("return vim.bo.filetype"), "malleable_confirm")
        c.keys("n")
        t.eq("No keeps the text", c.lines(), { "Maybe" })
        c.keys("<C-c><C-k>")
        c.keys("y")
        t.eq("Yes closes it", c.lua("return vim.bo.filetype"), "keelstatus")
        t.eq("nothing committed", count(t, repo), 1)
        c.keys("cc")
        t.eq("the text is gone", c.lines(), { "" })
    end)

    t.child(function(c) -- a failing hook keeps the message
        local repo = t.repo({ f = "a\n" })
        hook(t, repo, "pre-commit", 'echo "hook says no" >&2\nexit 1')
        t.write(repo, "f", "b\n")
        t.git(repo, "add", "f")
        c.open(repo)
        c.keys("cc")
        c.keys("Precious message<Esc>")
        c.keys("<C-c><C-c>")
        t.eq("hook blocks the commit", count(t, repo), 1)
        t.eq("buffer stays", c.lua("return vim.bo.filetype"), "gitcommit")
        t.eq("text stays", c.lines(), { "Precious message" })
        t.eq("still editable", c.lua("return vim.bo.modifiable"), true)
        t.ok("git's reason shown", c.lua([[return table.concat(notes, "\n"):find("hook says no", 1, true) ~= nil]]))
        vim.fn.delete(repo .. "/.git/hooks/pre-commit")
        c.keys("<C-c><C-c>")
        t.eq("retry commits", subject(t, repo), "Precious message")
    end)

    t.child(function(c) -- hooks see a normal git environment
        local repo = t.repo({ f = "a\n" })
        hook(t, repo, "pre-commit", 'printf "%s" "${GIT_LITERAL_PATHSPECS:-unset}" > .git/hook-env')
        t.write(repo, "f", "b\n")
        t.git(repo, "add", "f")
        c.open(repo)
        c.keys("cc")
        c.keys("Env check")
        c.keys("<C-c><C-c>")
        t.eq("hook has no literal pathspecs", t.read(repo, ".git/hook-env"), "unset")
    end)

    t.child(function(c) -- amend
        local repo = t.repo({ f = "a\n" })
        t.write(repo, "g", "new\n")
        t.git(repo, "add", "g")
        c.open(repo)
        c.keys("ca")
        t.eq("amend starts from the message", c.lines(), { "base" })
        t.eq("a filled message starts in Normal", c.mode(), "n")
        c.keys("A plus<Esc>")
        c.keys("<C-c><C-c>")
        t.eq("amend adds no commit", count(t, repo), 1)
        t.eq("amend changes the message", subject(t, repo), "base plus")
        t.ok("amend takes staged files", t.git(repo, "show", "--stat", "HEAD"):find("g", 1, true))
    end)

    t.child(function(c)
        local repo = t.repo()
        t.write(repo, "f", "a\n")
        t.git(repo, "add", "f")
        c.open(repo)
        c.keys("ca")
        t.eq("no amend before a commit", c.lua("return vim.bo.filetype"), "keelstatus")
        c.keys("cc")
        c.keys("First commit")
        c.keys("<C-c><C-c>")
        t.eq("first commit works", subject(t, repo), "First commit")
    end)

    t.child(function(c) -- a message is committed exactly
        local repo = staged(t, c)
        c.keys("cc")
        c.keys("Title<CR><CR># not a comment<Esc>")
        c.keys("<C-c><C-c>")
        t.eq("keeps a line starting with #", vim.trim(t.git(repo, "log", "-1", "--format=%B")),
            "Title\n\n# not a comment")
    end)
end
